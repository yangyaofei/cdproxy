  function normalize(lang) {
    if (!lang) return "en";
    return /^zh/i.test(String(lang).trim()) ? "zh" : "en";
  }

  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "zh" || saved === "en") return saved;
    } catch (e) {}
    const sys = (typeof navigator !== "undefined" && (navigator.language || (navigator.languages && navigator.languages[0]))) || "en";
    return normalize(sys);
  }

  function save(lang) {
    const norm = normalize(lang);
    try { localStorage.setItem(STORAGE_KEY, norm); } catch (e) {}
    if (typeof document !== "undefined" && document.documentElement) {
      document.documentElement.lang = norm === "zh" ? "zh-CN" : "en";
    }
    return norm;
  }

  function t(lang, key, params) {
    const norm = lang === "en" ? "en" : "zh";
    let text = (DICT[norm] && DICT[norm][key]) || DICT.zh[key] || key;
    if (params && typeof params === "object") {
      text = text.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : ""));
    }
    return text;
  }

  function translateLayoutDesc(lang, entry) {
    if (!entry) return "";
    if (lang !== "en") return entry.desc || "";
    const title = String(entry.title || "");
    if (DICT.en["layout." + title]) return DICT.en["layout." + title];
    if (title.includes(".agent-browser/config.json")) return DICT.en["layout.ab_config"];
    if (title.includes("pointer.json") || String(entry.desc || "").includes("数据目录指针")) return DICT.en["layout.pointer"];
    return entry.desc || "";
  }

  function translateConfigTitle(lang, file) {
    if (!file) return "";
    if (lang !== "en") return file.title || file.key || "";
    const k = "cfg." + (file.key || "");
    return DICT.en[k] || file.title || file.key || "";
  }

  function translateRuleNote(lang, note) {
    if (!note) return "";
    if (lang !== "en") return note;
    const key = DEFAULT_NOTE_KEYS[note];
    return key ? DICT.en[key] : note;
  }

